"""
This script processes output files generated by the ChromNAV software and compiles
them into a structured Excel database.

Each analysis channel is exported by ChromNAV as an individual CSV file. A set of
CSV files (representing multiple channels) is stored together in a folder referred
to as a *batch*. The script reads all channels in the batch, extracts peak-related
information (e.g., peak area, retention time, acquisition metadata), and organizes
the data into a clean, unified Excel workbook.

Usage:
    python process_chromnav_batch.py    --batch <path_to_batch_folder>
                                        --database <path_to_output_excel_file>

"""

import os
import argparse
from chroma_tool_py.io import merge_channels, update_xlsx_db


def main():
    parser = argparse.ArgumentParser(
        description="Process ChromNAV batch files to structured excel database"
    )
    # IO arguments
    parser.add_argument(
        "--batch",
        "-b",
        required=True,
        help="Batch folder containing the channel csv files",
    )
    parser.add_argument(
        "--database", "-db", required=True, help="Path of the excel database"
    )

    args = parser.parse_args()
    batch_folder = args.batch
    database_path = args.database

    # Extract the batch name from the
    batch_name = os.path.basename(os.path.normpath(batch_folder))

    # Column to be extracted from each channel file
    extract_cols = ["Acquisition Date", "Chromatogram Name", "CH", "Peak Name", "Area"]

    # Merge peak information into a single dataframe
    appended_df = merge_channels(batch_folder, extract_cols)

    # print(appended_df)

    # Load information into the database workbook
    update_xlsx_db(
        new_df=appended_df,
        workbook_path=database_path,
        sheet_name="TABLE",  # This is from the structured db in excel
        table_name="DataTable",  # This is from the structured db in excel
        batch_name=batch_name,
    )


if __name__ == "__main__":
    main()
